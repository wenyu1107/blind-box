def more_to_case(item):
    title, tags, story, evs, prompt, hint, answers, explain = item
    evidence = [ev(f"{chr(65+i)} · {name}", text) for i, (name, text) in enumerate(evs)]
    return dict(
        title=title,
        tags=tags,
        story=story,
        evidence=evidence,
        prompt=prompt,
        hint=hint,
        answers=answers,
        explain=explain,
    )


