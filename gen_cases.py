def ev(label: str, content: str) -> dict:
    return {"label": label, "content": content.strip()}


def make_case(idx, title, tags, story, evidence, prompt, hint, answers, explain):
    return {
        "id": f"case-{idx:03d}",
        "title": title,
        "tags": tags,
        "kind": "detective",
        "mode": "text",
        "requireDeepAll": False,
        "story": story.strip(),
        "evidence": evidence,
        "prompt": prompt,
        "placeholder": "交叉核对全部证物后再作答…",
        "hint": hint,
        "answers": answers,
        "explain": explain,
    }


def count_names(text: str, names: list) -> dict:
    return {n: len(re.findall(re.escape(n), text)) for n in names}


