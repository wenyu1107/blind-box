def compact_to_case(idx, title, tags, a, b, c, d, incident, culprit, explain):
    names = [a, b, c, d]
    # framed is first name typically
    story = (
        f"{incident}。现场初看证据指向多人，需交叉核对。\n\n"
        f"相关人：\n1）{a}\n2）{b}\n3）{c}\n4）{d}"
    )
    evidence = [
        ev(
            "证物 A · 权限与日志",
            f"系统/门锁初看指向{a}。\n\n初看：{a}嫌疑最大。",
            f"深入后发现账号或工具链实际控制者更接近{culprit}；{a}有可核验的不在场片段。",
        ),
        ev(
            "证物 B · 微量物证",
            f"现场留下像{b}常用的痕迹。",
            f"同类痕迹被证明可伪造；特征批次指向{culprit}的器材/耗材。",
        ),
        ev(
            "证物 C · 旁人轨迹",
            f"{c}与{d}各有说辞，混乱。",
            f"可排除者留下连续轨迹；{culprit}的空窗期与案发分钟级重合。",
        ),
        ev(
            "证物 D · 伪证",
            f"出现一份直接指控{a}的「铁证」。",
            f"铁证的存储/墨迹/元数据被篡改，篡改手法符合{culprit}的技能栈。",
        ),
        ev(
            "证物 E · 收束",
            "仍有两种解释都能说通。",
            explain,
        ),
    ]
    answers = [culprit]
    if culprit in names:
        answers.append(culprit)
    return dict(
        title=title,
        tags=tags,
        story=story,
        evidence=evidence,
        prompt=f"谁是造成「{incident}」的责任人？",
        hint=f"初看会指向{a}。先证伪那份「铁证」，再看工具链属于谁。",
        answers=list(dict.fromkeys(answers)),
        explain=explain,
    )


