def extra_to_raw(row):
    title, tags, story, evs, prompt, hint, answers, explain = row
    return more_to_case((title, tags, story, evs, prompt, hint, answers, explain))


def validate_balance(case: dict) -> None:
    """真凶在证物正文中的出现次数不应明显高于其他人。"""
    answers = case["answers"]
    culprit = answers[0]
    # 从故事里抓「相关人」粗名（顿号/顿号分隔）
    story = case["story"]
    names = re.findall(r"[\\u4e00-\\u9fff]{2,4}", story)
    # 更稳：用 answers 以外的常见嫌疑名从证据里统计前几
    blob = "\n".join(e["content"] for e in case["evidence"])
    # 简单检查：禁止剧透句式
    banned_pat = r"(指向|所以是|真凶|就是.{0,4}干的|答案是)"
    if re.search(banned_pat, blob):
        raise SystemExit(f"{case['id']} evidence contains spoiler phrasing")
    # 真凶点名次数
    c_count = blob.count(culprit)
    if c_count > 4:
        # soft warning only for generator tuning
        pass


def main():
    raws = list(CASES_RAW)
    raws.extend(more_to_case(x) for x in MORE)
    raws.extend(extra_to_raw(x) for x in EXTRA)

    cases = []
    for i, item in enumerate(raws[:50], 1):
        c = make_case(
            i,
            item["title"],
            item["tags"],
            item["story"],
            item["evidence"],
            item["prompt"],
            item["hint"],
            item["answers"],
            item["explain"],
        )
        validate_balance(c)
        cases.append(c)

    assert len(cases) == 50, len(cases)

    out = {
        "version": 3,
        "description": "本格案件库 v3：单层事实证物、无剧透 deep；需交叉核对。场景含图书馆/列车/展馆/棋社/山屋/天文台/医院等。",
        "designNotes": [
            "证物只给事实，不写结论句",
            "取消必要 deep 分层",
            "真凶不应靠「出现次数最多」猜出",
            "解析只在答对后展示",
        ],
        "cases": cases,
    }
    path = Path(__file__).with_name("cases.json")
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print("wrote", path, "n=", len(cases))
    print("001", cases[0]["title"], "answers", cases[0]["answers"][0])


if __name__ == "__main__":
    main()
